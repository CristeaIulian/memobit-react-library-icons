// Generates src/iconNames.ts — an explicit IconName union
// derived from the keys of `iconMap` in map.ts.
//
// Why: typing IconName as `keyof typeof iconMap` forced the bundled
// index.d.ts to embed the entire 475-entry iconMap object type, which
// dominated DTS build time. An explicit union keeps IconName flat.
//
// Run after editing map.ts: `npm run generate:icon-names`

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const iconMapPath = join(here, '../src/map.ts');
const outPath = join(here, '../src/iconNames.ts');

const source = readFileSync(iconMapPath, 'utf8');
const lines = source.split(/\r?\n/);

const startIndex = lines.findIndex((line) => line.includes('iconMap'));
if (startIndex === -1) {
    throw new Error('Could not locate the iconMap declaration in map.ts');
}

const keys = [];
const exportByName = new Map();
for (let i = startIndex + 1; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*}/.test(line)) break;

    const quoted = line.match(/^\s*'([^']+)'\s*:\s*([A-Za-z0-9_$]+)/);
    const unquoted = line.match(/^\s*([A-Za-z0-9_$]+)\s*:\s*([A-Za-z0-9_$]+)/);
    const shorthand = line.match(/^\s*([A-Za-z0-9_$]+)\s*,\s*$/);

    if (quoted) { keys.push(quoted[1]); exportByName.set(quoted[1], quoted[2]); }
    else if (unquoted) { keys.push(unquoted[1]); exportByName.set(unquoted[1], unquoted[2]); }
    else if (shorthand) { keys.push(shorthand[1]); exportByName.set(shorthand[1], shorthand[1]); }
}

const unique = [...new Set(keys)].sort();
if (unique.length === 0) {
    throw new Error('No icon keys were extracted — check the iconMap format');
}

const union = unique.map((key) => `    | '${key}'`).join('\n');
const output = `// AUTO-GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Run \`npm run generate:icon-names\` after changing map.ts.

export type IconName =
${union};
`;

writeFileSync(outPath, output);
console.log(`Wrote ${unique.length} icon names to ${outPath}`);

// A runtime counterpart to the IconName type. The Vite plugin needs to know every valid
// name, and which identifier each module exports, while it builds a trimmed map — and a
// type is gone by then. Plain data, so reading it costs no React import.
const modulesPath = join(here, '../src/iconModules.ts');
const entries = unique.map((key) => `    '${key}': '${exportByName.get(key)}',`).join('\n');
const modulesOutput = `// AUTO-GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Run \`npm run generate:icon-names\` after changing map.ts.
//
// Maps each icon name to the identifier its module exports. The name is also the module
// path: '@memobit/icons/icons/<name>'.

export const iconModules: Readonly<Record<string, string>> = {
${entries}
};

export const iconNameList: readonly string[] = Object.keys(iconModules);
`;
writeFileSync(modulesPath, modulesOutput);
console.log(`Wrote ${unique.length} icon module entries to ${modulesPath}`);
